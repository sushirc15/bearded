export interface GameItem {
  id: string;
  title: string;
  provider: string;
  category: "slots" | "live" | "originals" | "tournaments";
  rtp: string;
  volatility: "High" | "Very High" | "Medium" | "Extreme";
  maxWin: string;
  imageUrl: string;
  accent?: string;
  isPopular?: boolean;
  isFeatured?: boolean;
  playUrl: string;
}

export interface PoolInfo {
  count: number;
  updatedAt: string;
}

export interface TournamentItem {
  id: string;
  title: string;
  prizePool: string;
  status: "active" | "upcoming" | "ended";
  endsAt: string;
  participantsCount: number;
  featuredGame: string;
  minBet: string;
}

export interface SlotBattle {
  id: string;
  title: string;
  status: "live" | "voting" | "completed";
  gameA: {
    title: string;
    provider: string;
    score: number;
    votes: number;
    rtp: string;
    accent: string;
  };
  gameB: {
    title: string;
    provider: string;
    score: number;
    votes: number;
    rtp: string;
    accent: string;
  };
  roundTimeLeft: string;
  potPrize: string;
}

export interface GamesFilterOptions {
  category?: string;
  provider?: string;
  search?: string;
  limit?: number;
}

export interface GamesProvider {
  getGames(options?: GamesFilterOptions): Promise<GameItem[]>;
  getPoolInfo(): Promise<PoolInfo>;
  getRandomSlot(provider?: string): Promise<GameItem>;
  getTournaments(): Promise<TournamentItem[]>;
  getBattles(): Promise<SlotBattle[]>;
}

